-- Example Oracle release script with typical mixed content
CREATE SEQUENCE HR.SEQ_DEPARTMENT_ID START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;

CREATE TABLE HR.DEPARTMENT (
   DEPARTMENT_ID   NUMBER        NOT NULL,
   DEPT_CODE       VARCHAR2(10)  NOT NULL,
   DEPT_NAME       VARCHAR2(100) NOT NULL,
   MANAGER_ID      NUMBER,
   CREATED_DT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
   CREATED_BY      VARCHAR2(30),
   UPDATED_DT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
   UPDATED_BY      VARCHAR2(30),
   CONSTRAINT PK_DEPARTMENT PRIMARY KEY (DEPARTMENT_ID),
   CONSTRAINT UK_DEPARTMENT_CODE UNIQUE (DEPT_CODE)
) TABLESPACE HR_DATA;

ALTER TABLE HR.EMPLOYEE ADD (DEPARTMENT_ID NUMBER, HIRE_STATUS VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL);
ALTER TABLE HR.EMPLOYEE MODIFY (EMPLOYEE_NAME VARCHAR2(50));
ALTER TABLE HR.EMPLOYEE ADD CONSTRAINT FK_EMPLOYEE_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES HR.DEPARTMENT (DEPARTMENT_ID);
CREATE INDEX HR.IDX_EMPLOYEE_NAME ON HR.EMPLOYEE (EMPLOYEE_NAME) TABLESPACE HR_IDX;

CREATE OR REPLACE VIEW HR.EMPLOYEE_DEPT_VW AS
SELECT e.EMPLOYEE_ID, e.EMPLOYEE_NAME, d.DEPT_NAME
  FROM HR.EMPLOYEE e LEFT JOIN HR.DEPARTMENT d ON d.DEPARTMENT_ID = e.DEPARTMENT_ID;

CREATE OR REPLACE PROCEDURE HR.PRC_ASSIGN_DEPARTMENT (p_emp_id IN NUMBER, p_dept_id IN NUMBER) AS
BEGIN
    UPDATE HR.EMPLOYEE SET DEPARTMENT_ID = p_dept_id WHERE EMPLOYEE_ID = p_emp_id;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Employee not found');
    END IF;
END PRC_ASSIGN_DEPARTMENT;
/

INSERT INTO HR.DEPARTMENT (DEPARTMENT_ID, DEPT_CODE, DEPT_NAME) VALUES (1, 'IT', 'Information Technology');
UPDATE HR.EMPLOYEE SET DEPARTMENT_ID = 1 WHERE DEPARTMENT_ID IS NULL;
COMMIT;
