-- Add a cancellation reason to shadow orders
ALTER TABLE BILLING_EVENT.SHADOW_ORDER ADD (CANCEL_REASON VARCHAR2(200));

-- Lookup of active shadows by TTL
CREATE INDEX BILLING_EVENT.IDX_SHADOW_ORDER_TTL2 ON BILLING_EVENT.SHADOW_ORDER (TTL_EXPIRES_AT ASC) TABLESPACE "BILLING_EVENT_DATA";

-- New reference table
CREATE SEQUENCE BILLING_EVENT.SEQ_CANCEL_REASON_ID START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;

CREATE TABLE BILLING_EVENT.CANCEL_REASON (
   CANCEL_REASON_ID   NUMBER         NOT NULL,
   REASON_CODE        VARCHAR2(20)   NOT NULL,
   DESCRIPTION        VARCHAR2(200),
   CREATED_DT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
   CREATED_BY         VARCHAR2(30),
   UPDATED_DT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
   UPDATED_BY         VARCHAR2(30),
   CONSTRAINT PK_CANCEL_REASON PRIMARY KEY (CANCEL_REASON_ID),
   CONSTRAINT UK_CANCEL_REASON_CODE UNIQUE (REASON_CODE)
) TABLESPACE "BILLING_EVENT_DATA";

COMMENT ON TABLE BILLING_EVENT.CANCEL_REASON IS 'Reference list of shadow order cancellation reasons';

INSERT INTO BILLING_EVENT.CANCEL_REASON (CANCEL_REASON_ID, REASON_CODE, DESCRIPTION) VALUES (1, 'CUST_REQ', 'Customer request');
INSERT INTO BILLING_EVENT.CANCEL_REASON (CANCEL_REASON_ID, REASON_CODE, DESCRIPTION) VALUES (2, 'TTL', 'TTL expired');
COMMIT;

CREATE OR REPLACE TRIGGER BILLING_EVENT.TRG_CANCEL_REASON_BEFORE
BEFORE INSERT OR UPDATE ON BILLING_EVENT.CANCEL_REASON
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREATED_DT := CURRENT_TIMESTAMP;
        :NEW.CREATED_BY := SYS_CONTEXT('USERENV', 'SESSION_USER');
    END IF;
    :NEW.UPDATED_DT := CURRENT_TIMESTAMP;
    :NEW.UPDATED_BY := SYS_CONTEXT('USERENV', 'SESSION_USER');
END;
