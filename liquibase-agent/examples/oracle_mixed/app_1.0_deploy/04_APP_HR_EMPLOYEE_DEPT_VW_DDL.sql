CREATE OR REPLACE VIEW HR.EMPLOYEE_DEPT_VW AS
SELECT e.EMPLOYEE_ID, e.EMPLOYEE_NAME, d.DEPT_NAME
  FROM HR.EMPLOYEE e LEFT JOIN HR.DEPARTMENT d ON d.DEPARTMENT_ID = e.DEPARTMENT_ID;

