-- =====================================================
-- Table: SHADOW_PRODUCT_ORDER
-- Purpose: Individual ICOMS service codes from CBForce order
-- =====================================================
CREATE TABLE BILLING_EVENT.SHADOW_PRODUCT_ORDER (
   SHADOW_PRODUCT_ORDER_ID NUMBER             NOT NULL,
   SHADOW_ORDER_ID      NUMBER                NOT NULL,
   PRODUCT_ID           NUMBER                NOT NULL,
   PAID_QUANTITY        NUMBER(5)             DEFAULT 1,
   FREE_QUANTITY        NUMBER(5)             DEFAULT 0,
   CHECKED_IN_STATUS    VARCHAR2(1)           DEFAULT 'I',
   OCCURRENCE_NUMBER    NUMBER(10),
   PRODUCT_TYPE         VARCHAR2(1),
   PRODUCT_SEQUENCE     NUMBER(5),
   CATEGORY_CODE        VARCHAR2(1),
   CATEGORY_STATUS      VARCHAR2(1)           DEFAULT '2',
   CATEGORY_SEQUENCE    NUMBER(3),
   CREATED_DT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
   CREATED_BY           VARCHAR2(30)          NOT NULL,
   UPDATED_DT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
   UPDATED_BY           VARCHAR2(30)          NOT NULL,
   CONSTRAINT PK_SHADOW_SERVICE PRIMARY KEY (SHADOW_PRODUCT_ORDER_ID),
   CONSTRAINT FK_SHADOW_SVC_ORDER FOREIGN KEY (SHADOW_ORDER_ID)
      REFERENCES BILLING_EVENT.SHADOW_ORDER (SHADOW_ORDER_ID)
      ON DELETE CASCADE,
   CONSTRAINT FK_SHADOW_SVC_PRODUCT FOREIGN KEY (PRODUCT_ID)
      REFERENCES BILLING_EVENT.PRODUCT (PRODUCT_ID),
   CONSTRAINT UK_SHADOW_SVC_SEQ UNIQUE (SHADOW_ORDER_ID, PRODUCT_SEQUENCE),
   CONSTRAINT CHK_SHADOW_SVC_TYPE CHECK (PRODUCT_TYPE IN ('R', 'T')),
   CONSTRAINT CHK_SHADOW_CHECKED_IN CHECK (CHECKED_IN_STATUS IN ('I', 'A', 'D')),
   CONSTRAINT CHK_SHADOW_CATEGORY CHECK (CATEGORY_CODE IN ('C', 'T', 'D', 'W', 'H', 'S', 'L', 'M'))
)
TABLESPACE "BILLING_EVENT_DATA"
NOLOGGING;

